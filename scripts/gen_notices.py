"""Write THIRD_PARTY_NOTICES.md: every frontend package that ships in the built UI and every Python package in the app's
environment, with its license and license text. Run after changing dependencies, with `frontend/node_modules` present:

    python scripts/gen_notices.py
"""
from __future__ import annotations

import hashlib
import json
import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)", re.I)
HEADER = """# Third-party notices

Sage Study is MIT licensed (see `LICENSE`) and is built on the open-source packages below. Their licenses apply to those
packages. This file is generated by `scripts/gen_notices.py`.

Claude Code is **not** included with or redistributed by this app. Each user installs it separately from Anthropic, under
Anthropic's terms.

"""


def frontend_packages() -> list[dict]:
    lock = json.loads((FRONTEND / "package-lock.json").read_text(encoding="utf-8"))
    out = []
    for path, info in lock["packages"].items():
        if not path or info.get("dev"):
            continue
        folder = FRONTEND / path
        text = ""
        if folder.is_dir():
            names = sorted(p for p in folder.iterdir() if p.is_file() and LICENSE_FILE.match(p.name))
            text = "\n\n".join(p.read_text(encoding="utf-8", errors="replace") for p in names)
        license_name = info.get("license")
        if not license_name and (folder / "package.json").is_file():
            license_name = json.loads((folder / "package.json").read_text(encoding="utf-8")).get("license")
        out.append({"name": path.split("node_modules/")[-1], "version": info.get("version", ""), "license": license_name or "see package", "text": text})
    return sorted({(p["name"], p["version"]): p for p in out}.values(), key=lambda p: p["name"].lower())


def python_packages() -> list[dict]:
    wanted = {re.split(r"[=; ]", line)[0].strip().lower().replace("_", "-")
              for line in (ROOT / "constraints.txt").read_text(encoding="utf-8").splitlines() if line.strip()}
    out = []
    for dist in metadata.distributions():
        name = dist.metadata["Name"] or ""
        if name.lower().replace("_", "-") not in wanted:
            continue
        expression = dist.metadata.get("License-Expression")
        classifiers = [c.rsplit("::", 1)[-1].strip() for c in dist.metadata.get_all("Classifier") or [] if c.startswith("License ::")]
        raw = (dist.metadata.get("License") or "").strip()
        license_name = expression or ", ".join(classifiers) or (raw if len(raw) < 80 else "see text") or "see package"
        texts = [Path(dist.locate_file(f)).read_text(encoding="utf-8", errors="replace") for f in (dist.files or []) if LICENSE_FILE.match(f.name) and "dist-info" in str(f)]
        out.append({"name": name, "version": dist.version, "license": license_name, "text": "\n\n".join(texts)})
    return sorted({p["name"].lower(): p for p in out}.values(), key=lambda p: p["name"].lower())


def table(rows: list[dict]) -> str:
    lines = ["| Package | Version | License |", "| --- | --- | --- |"]
    lines += [f"| {r['name']} | {r['version']} | {r['license']} |" for r in rows]
    return "\n".join(lines)


def texts(rows: list[dict]) -> str:
    """One section per distinct license text, naming every package that uses it."""
    groups: dict[str, list[str]] = {}
    bodies: dict[str, str] = {}
    for r in rows:
        if not r["text"].strip():
            continue
        key = hashlib.sha256(r["text"].encode()).hexdigest()
        bodies[key] = r["text"].strip()
        groups.setdefault(key, []).append(f"{r['name']} {r['version']}")
    parts = []
    for key, names in groups.items():
        parts.append(f"### {', '.join(names)}\n\n```text\n{bodies[key].replace('```', '` ` `')}\n```")
    return "\n\n".join(parts)


def main() -> None:
    js, py = frontend_packages(), python_packages()
    copyleft = [r for r in js + py if re.search(r"\b(A?GPL)\b", r["license"]) and "LGPL" not in r["license"]]
    for r in copyleft:
        print(f"CHECK THIS LICENSE: {r['name']} {r['version']}: {r['license']}")
    body = (HEADER + "## Frontend packages (included in the built UI)\n\n"
            "Includes KaTeX, Monaco Editor, Mermaid, Recharts (the chart library), React, and their dependencies. The Inter typeface is under the SIL Open Font License.\n\n"
            + table(js) + "\n\n## Python packages\n\n" + table(py) + "\n\n## License texts\n\n" + texts(js + py) + "\n")
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {len(js)} frontend and {len(py)} Python packages")


if __name__ == "__main__":
    main()
